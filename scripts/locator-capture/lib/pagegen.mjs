// Generates WebdriverIO page classes from the screen JSON files.
import fs from 'node:fs';
import path from 'node:path';

export function detectFormat(pref, cwd = process.cwd()) {
  if (pref === 'esm' || pref === 'cjs') return pref;
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(cwd, 'package.json'), 'utf8'));
    return pkg.type === 'module' ? 'esm' : 'cjs';
  } catch {
    return 'esm';
  }
}

const q = (s) => JSON.stringify(s);

const BASE_BODY = `
  constructor(locators, anchors) {
    this.locators = locators;
    this.anchors = anchors;
  }

  /** Element by name, trying the primary locator first, then fallbacks. */
  async find(name, { timeout = 5000 } = {}) {
    const selectors = this.locators[name];
    if (!selectors) throw new Error(\`\${this.constructor.name}: unknown element "\${name}"\`);
    const deadline = Date.now() + timeout;
    do {
      for (const sel of selectors) {
        const el = await $(sel);
        if (await el.isExisting()) return el;
      }
      await browser.pause(250);
    } while (Date.now() < deadline);
    throw new Error(\`\${this.constructor.name}: "\${name}" not found with \${selectors.length} locator(s)\`);
  }

  /** True when the screen's anchor elements are present. */
  async isOpen() {
    for (const name of this.anchors) {
      const el = await $(this.locators[name][0]);
      if (!(await el.isExisting())) return false;
    }
    return this.anchors.length > 0;
  }

  async waitForOpen(timeout = 15000) {
    await browser.waitUntil(() => this.isOpen(), {
      timeout,
      timeoutMsg: \`\${this.constructor.name} did not open within \${timeout}ms\`,
    });
    return this;
  }
`;

function baseFile(format) {
  const header = '// AUTO-GENERATED by scripts/locator-capture. Safe to edit; it is only created if missing.\n';
  return format === 'esm'
    ? `${header}export default class BasePage {${BASE_BODY}}\n`
    : `${header}class BasePage {${BASE_BODY}}\n\nmodule.exports = BasePage;\n`;
}

// Tokens (ids / descriptions) seen on more than one screen: toolbars, bottom nav, etc.
function sharedTokens(outputDir) {
  const freq = new Map();
  try {
    const index = JSON.parse(fs.readFileSync(path.join(outputDir, '_screens.json'), 'utf8'));
    for (const s of Object.values(index.screens)) for (const t of s.signature) freq.set(t, (freq.get(t) || 0) + 1);
  } catch {}
  return new Set([...freq].filter(([, n]) => n > 1).map(([t]) => t));
}

function pickAnchors(elements, shared = new Set()) {
  // Up to 3 elements with unique, stable locators that exist only on this screen
  const ok = Object.entries(elements).filter(([, e]) => {
    const a = e.attributes || {};
    if (!e.primary?.unique || e.primary.note || !['id', 'accessibility id'].includes(e.primary.strategy)) return false;
    if (/Layout$|Toolbar|AppBar|RecyclerView|ScrollView/.test(a.class || '')) return false;
    return !shared.has('id:' + a.resourceId) && !shared.has('desc:' + a.contentDesc);
  });
  // Prefer inputs and buttons
  ok.sort(([, x], [, y]) => (y.attributes?.input ? 2 : y.attributes?.clickable ? 1 : 0) - (x.attributes?.input ? 2 : x.attributes?.clickable ? 1 : 0));
  return ok.slice(0, 3).map(([n]) => n);
}

export function renderPage(data, format, shared) {
  const cls = data.screen;
  const entries = Object.entries(data.elements);
  const locs = entries
    .map(([n, e]) => `  ${n}: [${[e.primary, ...(e.fallbacks || [])].filter((l) => !l.note?.startsWith('absolute')).map((l) => q(l.selector)).join(', ') || q(e.primary.selector)}],`)
    .join('\n');
  const getters = entries
    .map(([n, e]) => {
      const a = e.attributes || {};
      const label = [a.class?.split('.').pop(), a.text && `"${a.text.slice(0, 40)}"`, !e.primary.unique && 'NOT UNIQUE - review']
        .filter(Boolean)
        .join(' ');
      return `  /** ${label.replace(/\*\//g, '* /')} */\n  get ${n}() {\n    return $(L.${n}[0]);\n  }`;
    })
    .join('\n\n');
  const anchors = pickAnchors(data.elements, shared);

  const header = `// AUTO-GENERATED from locators/${cls}.json by scripts/locator-capture.
// Do not edit: it is regenerated on every capture. Extend this class for actions, e.g.
//   class Login extends ${cls}Class { async login(phone) { ... } }
// Screen: ${data.title || '(no title)'} | activity: ${data.activity || '-'} | updated: ${data.lastCaptured}
`;
  const body = `
const L = {
${locs}
};

class ${cls} extends BasePage {
  constructor() {
    super(L, ${JSON.stringify(anchors)});
  }

${getters}
}
`;
  return format === 'esm'
    ? `${header}import BasePage from './BasePage.js';\n${body}\nexport { ${cls} as ${cls}Class, L as ${cls}Locators };\nexport default new ${cls}();\n`
    : `${header}const BasePage = require('./BasePage.js');\n${body}\nmodule.exports = new ${cls}();\nmodule.exports.${cls}Class = ${cls};\nmodule.exports.${cls}Locators = L;\n`;
}

export function writePage(outputDir, data, format) {
  const dir = path.join(outputDir, 'pages');
  fs.mkdirSync(dir, { recursive: true });
  const base = path.join(dir, 'BasePage.js');
  if (!fs.existsSync(base)) fs.writeFileSync(base, baseFile(format));
  const file = path.join(dir, `${data.screen}.page.js`);
  fs.writeFileSync(file, renderPage(data, format, sharedTokens(outputDir)));
  return file;
}

export function writeAllPages(outputDir, store, format) {
  return Object.keys(store.index.screens).map((n) => writePage(outputDir, store.load(n), format));
}
